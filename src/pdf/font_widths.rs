/// Look up the width table for a standard 14 font by name.
/// Returns the width array and whether it uses WinAnsiEncoding (true) or
/// a font-specific encoding (false, for Symbol and ZapfDingbats).
///
/// For Courier variants, returns None since all widths are the constant 600.
pub fn standard_14_widths(font_name: &str) -> Option<&'static [u16; 256]> {
    // Strip subset prefix (e.g., "ABCDEF+Helvetica" -> "Helvetica")
    let base = if let Some(pos) = font_name.find('+') {
        &font_name[pos + 1..]
    } else {
        font_name
    };
    match base {
        "Helvetica" | "Helvetica-Oblique" => Some(&HELVETICA_WIDTHS),
        "Helvetica-Bold" | "Helvetica-BoldOblique" => Some(&HELVETICA_BOLD_WIDTHS),
        "Times-Roman" => Some(&TIMES_ROMAN_WIDTHS),
        "Times-Bold" => Some(&TIMES_BOLD_WIDTHS),
        "Times-Italic" => Some(&TIMES_ITALIC_WIDTHS),
        "Times-BoldItalic" => Some(&TIMES_BOLDITALIC_WIDTHS),
        "Symbol" => Some(&SYMBOL_WIDTHS),
        "ZapfDingbats" => Some(&ZAPF_DINGBATS_WIDTHS),
        _ => None, // Courier variants or unknown
    }
}

/// Check if a font name is a Courier variant (monospaced, all widths 600).
pub fn is_courier(font_name: &str) -> bool {
    let base = if let Some(pos) = font_name.find('+') {
        &font_name[pos + 1..]
    } else {
        font_name
    };
    matches!(
        base,
        "Courier" | "Courier-Bold" | "Courier-Oblique" | "Courier-BoldOblique"
    )
}

